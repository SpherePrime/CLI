import sharp from 'sharp'
import { writeFile } from 'node:fs/promises'
const svg = new URL('../build/icon.svg', import.meta.url)
const png = await sharp(svg.pathname.replace(/^\/(\w:)/, '$1'))
  .resize(256, 256)
  .png()
  .toBuffer()
await writeFile(new URL('../build/icon.png', import.meta.url), png)
const header = Buffer.alloc(22)
header.writeUInt16LE(1, 2)
header.writeUInt16LE(1, 4)
header.writeUInt16LE(1, 10)
header.writeUInt16LE(32, 12)
header.writeUInt32LE(png.length, 14)
header.writeUInt32LE(22, 18)
await writeFile(new URL('../build/icon.ico', import.meta.url), Buffer.concat([header, png]))
console.log('SpherePrime icons built')
